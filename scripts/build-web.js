const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const out = path.join(root, 'dist');

const publicFiles = [
  'index.html',
  'app.js',
  'style.css',
  'chart.js',
  'sync.js',
  'manifest.json',
  'firebase-config.js',
  'firebase.js',
  'auth.js',
  'attendance_template.xlsx',
  'TBTA-2026-2027-RHS-Attendance-And-Homework-Template.xlsx'
];

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

for (const file of publicFiles) {
  const source = path.join(root, file);
  if (!fs.existsSync(source)) throw new Error(`Required web asset is missing: ${file}`);
  fs.copyFileSync(source, path.join(out, file));
}

// Legacy Google Sheets/Drive synchronization stays disabled throughout the
// Firebase migration until the dedicated synchronization phase is approved.
fs.writeFileSync(path.join(out, 'sync-config.js'), `// Generated by scripts/build-web.js\nwindow.ATTENDANCE_SYNC_CONFIG = {\n  mode: "disabled",\n  googleDriveUrl: ""\n};\n`);

// Security headers for Cloudflare Workers Static Assets.
fs.writeFileSync(path.join(out, '_headers'), `/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin\n  X-Frame-Options: DENY\n  Permissions-Policy: camera=(), microphone=(), geolocation=()\n  Cache-Control: no-cache\n\n/*.js\n  Cache-Control: no-cache\n\n/*.css\n  Cache-Control: no-cache\n`);

console.log('Web build complete: dist/');
console.log('Published files:', [...publicFiles, 'sync-config.js', '_headers'].join(', '));
